/**
 * Regenerates the committed E2EE fixtures.
 *
 * Run with `npm run fixtures:e2ee`. Writes:
 *
 *   * `test/fixtures/e2ee-written-vault.json`    -- E2EE, plaintext document ids
 *   * `test/fixtures/e2ee-obfuscated-vault.json` -- E2EE + path obfuscation
 *
 * These are the closest thing to plugin-generated fixtures that can be produced
 * without installing Obsidian: the ciphertext, the chunk ids, the encrypted
 * metadata envelope and the obfuscated document ids are all produced by
 * `octagonal-wheels` and `livesync-commonlib` through the real sidecar. Only the
 * *database* is a mock -- and CouchDB does not participate in the codec, it just
 * stores what it is given.
 *
 * What the committed dumps buy over the round-trip tests: `test/e2ee.test.mjs`
 * reads them back with a *fresh* sidecar and no writing involved, so if a
 * commonlib bump changes the key schedule, the chunk-id derivation, the HKDF
 * header or the metadata envelope, the read fails. A round trip alone cannot
 * catch that -- it would happily write and read a new, mutually consistent, wrong
 * format.
 *
 * Regenerate ONLY on a deliberate commonlib bump, and treat the diff as the
 * signal to review `maxSchemaVersion`. Never hand-edit the JSON: a fixture edited
 * to make a test pass proves nothing about the format.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { withCouch } from "./harness.mjs";
import { PBKDF2_SALT, writableVault } from "./fixtures.mjs";
import {
    E2EE_BINARY_BYTES,
    E2EE_BINARY_PATH,
    E2EE_FIXTURE_PATH,
    E2EE_OBFUSCATED_FIXTURE_PATH,
    E2EE_OBFUSCATED_PATH,
    E2EE_OBFUSCATE_PASSPHRASE,
    E2EE_PASSPHRASE,
    E2EE_PLAIN_PATH,
    E2EE_TEXT,
} from "./e2ee-fixture.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const commonlibVersion = require("@vrtmrz/livesync-commonlib/package.json").version;

/**
 * Writes `entries` through a read-write sidecar and dumps the resulting database.
 *
 * @param {string} fixturePath
 * @param {object} e2ee passphrase, and optionally obfuscatePassphrase
 * @param {Array<{path: string, content: object}>} entries
 */
async function generate(fixturePath, e2ee, entries, notes) {
    await withCouch(
        { vault: writableVault(), writable: true, mode: "read-write", e2ee },
        async ({ couch, open }) => {
            const { sidecar, initializeResult } = await open();
            if (initializeResult.compatibility.status !== "ok") {
                throw new Error(`writer refused the vault: ${JSON.stringify(initializeResult.compatibility)}`);
            }
            const expect = {};
            for (const entry of entries) {
                const result = await sidecar.call("write", { ...entry, baseRev: null });
                expect[entry.path] = { kind: result.kind, size: result.size, rev: result.rev };
            }

            const dump = {
                $comment:
                    "GENERATED by npm run fixtures:e2ee -- do not hand-edit. Real ciphertext produced by livesync-commonlib/octagonal-wheels through the sidecar.",
                $notes: notes,
                generatedAt: new Date().toISOString(),
                commonlibVersion,
                pluginVersionTested: initializeResult.supported.pluginVersionTested,
                schemaVersion: initializeResult.remote.schemaVersion,
                passphrase: E2EE_PASSPHRASE,
                ...(e2ee.obfuscatePassphrase ? { obfuscatePassphrase: e2ee.obfuscatePassphrase } : {}),
                pbkdf2salt: PBKDF2_SALT,
                expect,
                docs: Object.fromEntries(couch.docs),
                localDocs: Object.fromEntries(couch.localDocs),
            };

            const target = path.resolve(here, "..", fixturePath);
            mkdirSync(path.dirname(target), { recursive: true });
            writeFileSync(target, `${JSON.stringify(dump, null, 2)}\n`);
            process.stderr.write(`wrote ${fixturePath}: ${couch.docs.size} documents\n`);
        }
    );
}

await generate(
    E2EE_FIXTURE_PATH,
    { passphrase: E2EE_PASSPHRASE },
    [
        { path: E2EE_PLAIN_PATH, content: { kind: "text", text: E2EE_TEXT } },
        { path: E2EE_BINARY_PATH, content: { kind: "binary", base64: E2EE_BINARY_BYTES.toString("base64") } },
    ],
    "Encrypted chunks (h:+) under plaintext document ids. The pre-existing plaintext " +
        "chunks come from test/fixtures.mjs smallVault(), so this doubles as a mixed " +
        "encrypted/unencrypted vault: upstream classifies a chunk by its id prefix and " +
        "e_ marker, not by a vault-wide flag."
);

await generate(
    E2EE_OBFUSCATED_FIXTURE_PATH,
    { passphrase: E2EE_PASSPHRASE, obfuscatePassphrase: E2EE_OBFUSCATE_PASSPHRASE },
    [{ path: E2EE_OBFUSCATED_PATH, content: { kind: "text", text: E2EE_TEXT } }],
    "Path obfuscation: the entry lives under an f: id with its path/mtime/ctime/size " +
        "in an encrypted envelope. Only the obfuscated entry is addressable by path -- " +
        "path2id obfuscates unconditionally once the passphrase is set, so the plaintext-id " +
        "entries inherited from smallVault() cannot be read by name. A real obfuscated " +
        "vault has none of those; the plugin requires a rebuild to switch modes."
);
